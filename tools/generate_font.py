# Letters met accent: accent op rij 0, letter (kleine letter) op rij 2..6
ACCENTS = {"grave": ".#...", "acute": "...#.", "uml": ".#.#.", "circ": "..#.."}
for ch, base, acc in [("è", "e", "grave"), ("é", "e", "acute"), ("ë", "e", "uml"), ("ê", "e", "circ"),
                      ("à", "a", "grave"), ("á", "a", "acute"), ("ä", "a", "uml"),
                      ("ó", "o", "acute"), ("ò", "o", "grave"), ("ö", "o", "uml"),
                      ("ú", "u", "acute"), ("ü", "u", "uml"), ("í", "i", "acute"), ("ï", "i", "uml")]:
    rows = G[base].split("|")
    if base == "i":
        rows = [".....", ".....", ".##..", "..#..", "..#..", "..#..", ".###."]
    G[ch] = "|".join([ACCENTS[acc], "....."] + rows[2:])


def glyph_name(ch):
    return "space" if ch == " " else "uni%04X" % ord(ch)


def draw_glyph(rows):
    pen = TTGlyphPen(None)
    for r, row in enumerate(rows):
        y0 = (6 - r) * PX
        c = 0
        while c < len(row):           # opeenvolgende pixels in een rij = één rechthoek
            if row[c] == "#":
                start = c
                while c < len(row) and row[c] == "#":
                    c += 1
                x0, x1, y1 = start * PX, c * PX, y0 + PX
                pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0))
                pen.closePath()
            else:
                c += 1
    return pen.glyph()


def main():
    chars = sorted(G.keys(), key=ord)
    order = [".notdef"] + [glyph_name(c) for c in chars]
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap({ord(c): glyph_name(c) for c in chars})
    glyphs = {".notdef": draw_glyph(["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"])}
    for c in chars:
        glyphs[glyph_name(c)] = draw_glyph(G[c].split("|"))
    fb.setupGlyf(glyphs)
    metrics = {}
    for name in order:
        g = glyphs[name]
        g.recalcBounds(fb.font["glyf"]) if hasattr(g, "recalcBounds") else None
        metrics[name] = (ADV, getattr(g, "xMin", 0) or 0)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=800, descent=-200)
    fb.setupNameTable({"familyName": "Dauwpixel", "styleName": "Regular",
                       "copyright": "Eigen werk voor het Lufia-prototype (vrij te gebruiken)"})
    fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, sTypoLineGap=0,
                usWinAscent=800, usWinDescent=200, xAvgCharWidth=ADV)
    fb.setupPost(isFixedPitch=1)
    out = os.path.join(ROOT, "assets", "fonts", "Dauwpixel-Regular.ttf")
    fb.save(out)
    print("Font opgeslagen:", out, "(%d tekens)" % len(chars))


if __name__ == "__main__":
    main()
